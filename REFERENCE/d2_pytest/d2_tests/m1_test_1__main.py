# 1. ASSERT
# ----------------------------------------------------------------------------------------------------------------------
# pytest переписывает байт-код assert, показывая значения переменных.
def test__assert_with_message():
    x = 42
    y = 7
    # Ошибка покажет значения x, y и всё выражение.
    # assert x // y == 5  # 42 // 7 = 6, не 5
    # Для демонстрации оставляем проходящим:
    assert x // y == 6


def test__collection_types():
    lst = [1, 2, 3]
    # Сравнение списков – видна разница.
    assert lst == [1, 2, 333]  # упадёт, показывая где отличие


