# ---------------------------------------------------------------------------
# 18.6 Пропуск класса по результату другого теста (вне класса)
# ---------------------------------------------------------------------------
# Правильный подход: хранить состояние в глобальной переменной модуля
# (или в pytest.stash), и в setup_class проверять это состояние.
# Примечание: порядок тестов в рамках файла гарантирован,
# но при распределённом запуске (pytest-xdist) это может нарушиться.

_previous_test_passed = False


def test__prerequisite():
    global _previous_test_passed
    # Имитируем, что какой-то важный предусловительный тест прошёл
    _previous_test_passed = True
    assert True


class Test__DependentOnPrevious:
    @classmethod
    def setup_class(cls):
        if not _previous_test_passed:
            pytest.skip("Предварительный тест не прошёл — класс пропущен")

    def test_needs_prereq(self):
        assert True  # выполнится, только если _previous_test_passed == True


# Альтернатива: использовать request.config.cache или pytest.stash
# (доступно в фикстурах) для межтестового общения, что безопаснее глобальных переменных.
@pytest.fixture(scope="session", autouse=True)
def store_prereq(request):
    # Записываем результат в stash (доступен в любой точке сессии)
    yield
    request.config.stash["prereq_passed"] = True  # устанавливаем в teardown как пример


