# ---------------------------------------------------------------------------
# 18.8 Важные предостережения и частые ошибки
# ---------------------------------------------------------------------------
# - Глобальные переменные для межтестового общения: порядок тестов
#   может измениться, если использовать случайный порядок (--random-order),
#   или при параллельном запуске. Лучше избегать таких зависимостей.
#
# - pytest.skip() в setup_method / setup_class работает, но в teardown методах
#   вызывать skip нельзя — будет ошибка.
#
# - pytest.exit() выбрасывает специальное исключение; если обернуть его
#   в try/except, поведение может стать неожиданным.
#
# - Если фикстура с autouse вызывает skip, то все тесты, попадающие в её область,
#   будут пропущены. Это удобно, но может скрыть проблемы с конфигурацией.


