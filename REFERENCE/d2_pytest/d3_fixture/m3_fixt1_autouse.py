# 46.4 Порядок выполнения: autouse и явные фикстуры
# ---------------------------------------------------------------------------
# Все фикстуры (включая autouse) образуют граф зависимостей.
# Явно запрошенная фикстура вычисляется в том же порядке, что и autouse,
# если они не зависят друг от друга. Порядок не гарантирован, если нет
# явных зависимостей.

@pytest.fixture
def base():
    return "base"

@pytest.fixture(autouse=True)
def logging_fixture():
    print("\n[autouse]")

def test_example(base):
    print(f"\n[test] base={base}")
# Может выполниться сначала logging_fixture, потом base, потом тест,
# или наоборот. Не стоит полагаться на порядок без явных `request`.

# Чтобы гарантировать порядок, используйте зависимости:
@pytest.fixture
def db():
    return "db"

@pytest.fixture(autouse=True)
def audit(db):  # зависит от db
    print(f"audit: {db}")
    return

def test_order():
    pass
# Теперь db будет выполнена до audit, так как audit требует db.


