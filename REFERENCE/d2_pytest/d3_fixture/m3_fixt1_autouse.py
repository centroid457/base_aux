# =============================================================================
# 46. AUTOTUE-ФИКСТУРЫ: ПОЛНОЕ РУКОВОДСТВО И BEST PRACTICES
# =============================================================================
# autouse=True заставляет фикстуру выполняться автоматически перед каждым
# тестом, без явного указания в сигнатуре тестовой функции. Это мощный,
# но опасный инструмент. Ниже — правила, приёмы и частые грабли.

# ---------------------------------------------------------------------------
# 46.5 Частые ошибки и как их избежать
# ---------------------------------------------------------------------------
# 1. Тяжёлые вычисления в autouse для каждого теста без необходимости.
#    Например, создание клиента БД, который нужен только 10% тестов.
#    Решение: использовать явные фикстуры или scope="module"/"session".

# 2. Неявное изменение глобального состояния, которое потом забывают.
#    Тест перестаёт работать при изолированном запуске.
#    Решение: документировать, что делает autouse, и возвращать явные значения.

# 3. Попытка параметризации autouse-фикстуры.
#    autouse с параметрами вызовет выполнение фикстуры для каждого набора
#    параметров для каждого теста, что почти всегда нежелательно.
#    Если нужна параметризация — не делайте autouse.

# 4. Использование autouse в conftest.py высокого уровня.
#    Фикстура будет действовать на всю директорию и поддиректории,
#    что может замедлить все тесты. Лучше размещать autouse только там,
#    где она действительно нужна, и с максимально широким scope.

# 5. Забытый return/yield в autouse-фикстуре.
#    Если фикстура ничего не возвращает — это нормально, она побочная.
#    Но если внутри есть yield, а код после yield делает важную очистку,
#    будьте уверены, что он выполняется вовремя.

# ---------------------------------------------------------------------------
# 46.6 BEST PRACTICES
# ---------------------------------------------------------------------------
# - **Используйте autouse только для сквозной функциональности**:
#   логирование, замер времени, установка random seed, управление
#   глобальными переменными окружения (с monkeypatch).
# - **Предпочитайте явные фикстуры** для ресурсов, которые нужны
#   конкретным тестам. Это улучшает читаемость и изоляцию.
# - **Для классов** используйте autouse scope="class" как замену setup_class,
#   когда вам нужны фикстурные возможности (yield, другие фикстуры).
# - **Документируйте autouse-фикстуры** — ставьте комментарий, почему она
#   именно автоматическая.
# - **При вставке в класс** не забывайте, что метод autouse-фикстуры должен
#   принимать `self` (если это метод класса) или `request` (если внешняя).
# - **При параллельном запуске** (xdist) помните, что scope="session"
#   autouse-фикстура будет выполняться в каждом воркере независимо.

