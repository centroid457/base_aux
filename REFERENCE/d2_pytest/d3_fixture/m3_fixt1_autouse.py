# 46.3 Область видимости (scope) и autouse
# ---------------------------------------------------------------------------
# scope="function" (по умолчанию) — выполняется перед каждым тестом.
# scope="class" — один раз на класс (setUpClass/tearDownClass).
# scope="module" — один раз на модуль.
# scope="session" — один раз на сессию.

@pytest.fixture(scope="class", autouse=True)
def setup_class_resource():
    """Аналог setup_class, но с поддержкой yield."""
    print("\n[class autouse] инициализация класса")
    yield
    print("\n[class autouse] очистка класса")

class TestOne:
    def test_a(self): pass
    def test_b(self): pass

class TestTwo:
    def test_c(self): pass


# ВАЖНО: scope="module" autouse-фикстура, определённая внутри класса,
# будет выполняться на уровне модуля, а не класса. Для класса используйте
# scope="class" либо определите фикстуру внутри класса (без scope,
# тогда она function-scoped, но если autouse — для каждого теста).


