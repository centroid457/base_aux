# ----------------------------------------------------------------------------------------------------------------------
device: str | None = None


def test_1_incorrect():
    global device
    device = "detected"
    assert device    # OK


def test_2_incorrect():
    assert device     # УПАДЕТ!!! НЕТ!!! вообщето работает!!!


