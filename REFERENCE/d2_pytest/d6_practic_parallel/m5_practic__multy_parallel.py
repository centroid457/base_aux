# 38. ПАРАЛЛЕЛЬНЫЙ ЗАПУСК, УСТРОЙСТВА И ЗАВИСИМОСТИ
# =============================================================================
# Вопросы организации тестов при работе с реальным оборудованием (UART, блоки питания и т.п.)
# Рассмотрим типичные ситуации и способы решения средствами pytest.

# ---------------------------------------------------------------------------
# 1. Независимые тесты (алгоритмы, данные) – xdist отлично подходит
# ---------------------------------------------------------------------------
# Если тесты не разделяют никаких ресурсов (файлы, порты, железо), можно
# смело использовать pytest-xdist для параллельного выполнения на нескольких ядрах.
#   pip install pytest-xdist
#   pytest -n auto
# Это даст прирост скорости практически на всех CPU‑bound задачах.

# ---------------------------------------------------------------------------
# 2. Одно устройство на UART – параллельный запуск бесполезен
# ---------------------------------------------------------------------------
# UART (COM‑порт) – эксклюзивный ресурс. Два теста не могут одновременно
# читать/писать в один и тот же порт. xdist, запускающий тесты в разных
# процессах, только создаст гонку и ошибки.
# Выход – выполнять тесты последовательно, либо использовать общую фикстуру
# с блокировкой (например, file lock) – но это сведёт на нет параллелизм.
# Поэтому для одного UART‑устройства xdist не даёт выигрыша.

# ---------------------------------------------------------------------------
# 3. Несколько устройств (UART1, UART2…) – как запускать?
# ---------------------------------------------------------------------------
# Если в системе динамически определяется несколько однотипных устройств,
# можно параметризовать тесты по списку доступных портов и выполнять их
# последовательно (для каждого устройства по очереди) или параллельно,
# выделяя каждому устройству отдельный процесс, но не смешивая их.

