# Вариант Б: xdist с распределением по устройствам (scope=device)
# Можно запустить несколько воркеров, каждый из которых «монопольно» владеет
# одним устройством. Для этого используется фикстура с scope="session",
# которая ищет свободное устройство и возвращает его. Тогда в одном воркере
# тесты будут выполняться последовательно для своего устройства, а воркеры
# работают параллельно.
# Это требует ручной блокировки при выборе устройства (через файловые замки
# или redis), но паттерн рабочий.

# ---------------------------------------------------------------------------
# 4. Много устройств + внешнее оборудование (источник напряжения)
# ---------------------------------------------------------------------------
# Здесь есть ресурсы, требующие синхронизации:
#   - источник питания: некоторые тесты должны переключать напряжение,
#     другие должны ждать, третьи не должны мешать измерениям тока.
#   - сами UART‑порты независимы (если устройств несколько), но общее
#     питание может создавать взаимное влияние.
#
# Подходы:
#   4.1) Разделить тесты на группы по уровню взаимодействия с питанием.
#        Использовать маркеры: @pytest.mark.independent, @pytest.mark.need_power_control.
#   4.2) Управлять питанием через фикстуру с блокировкой (threading.Lock или file lock).
#        Тогда тесты, помеченные как нуждающиеся в эксклюзивном доступе к питанию,
#        будут ждать освобождения ресурса.
#   4.3) Если тесты категорически нельзя смешивать, можно вынести их в отдельные
#        pytest‑сессии и запускать последовательно через makefile/скрипт.
#   4.4) Использовать pytest-ordering или pytest-dependency для гарантии порядка.

# Пример фикстуры с блокировкой источника питания (псевдокод):
import threading
