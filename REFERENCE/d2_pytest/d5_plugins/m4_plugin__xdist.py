# Обычно достаточно -v для отслеживания хода выполнения.

# ---------------------------------------------------------------------------
# 40.7 Совместимость с другими плагинами
# ---------------------------------------------------------------------------
# pytest-timeout: таймаут накладывается на тест внутри воркера, работает корректно.
# pytest-ordering: порядок гарантируется только внутри одного воркера.
# pytest-dependency: зависимости не работают между воркерами.
# pytest-rerunfailures: перезапуски работают внутри воркера.
# pytest-html / pytest-json-report: отчёты объединяются при использовании одного файла.

# ---------------------------------------------------------------------------
# 40.8 Отладка и проблемы
# ---------------------------------------------------------------------------
# --pdb не работает с xdist (тесты в отдельных процессах). Используйте обычный запуск.
# Если тест завис, можно убить воркеры через Ctrl+C — xdist прервёт все процессы.
# Для поиска виновника зависания можно использовать --timeout.
# При падении воркера он автоматически перезапускается (--max-worker-restart=N).

# ---------------------------------------------------------------------------
# 40.9 Практические сценарии
# ---------------------------------------------------------------------------
# 1) Много независимых вычислительных тестов (алгоритмы):
#    pytest -n auto
# 2) Тесты с UART: если устройств несколько и каждое подключается к своему порту,
#    можно параметризовать тесты по портам и использовать --dist=loadscope,
#    чтобы все тесты для одного порта шли в одном воркере.
# 3) Если есть только одно устройство — параллельный запуск не даст выигрыша.

# ---------------------------------------------------------------------------
# 40.10 Конфигурация в pytest.ini
# ---------------------------------------------------------------------------
# [pytest]
# addopts = -n auto
# Это приведёт к тому, что pytest всегда будет запускаться параллельно.
# Будьте осторожны, если ваши тесты не готовы к параллелизму.

