
# =============================================================================
# 40. PYTEST-XDIST: ПАРАЛЛЕЛЬНОЕ ВЫПОЛНЕНИЕ ТЕСТОВ
# =============================================================================
# Плагин pytest-xdist позволяет запускать тесты параллельно в нескольких
# процессах (воркерах), ускоряя прогон на многоядерных машинах.
# Установка: pip install pytest-xdist

import pytest
import time
import os

# ---------------------------------------------------------------------------
# 40.1 Базовый запуск: количество воркеров
# ---------------------------------------------------------------------------
# Запуск на всех доступных ядрах:
# pytest -n auto

# Запуск на фиксированном количестве процессов:
# pytest -n 4

# Запуск с передачей дополнительных аргументов:
# pytest -n 4 -v

# ---------------------------------------------------------------------------
# 40.2 Стратегии распределения тестов (--dist)
# ---------------------------------------------------------------------------
# Каждый воркер получает свой набор тестов. Способ распределения:
# --dist=load        (по умолчанию) — балансировка по времени выполнения тестов.
# --dist=loadscope   — тесты из одного scope (модуля или класса) идут в один воркер.
# --dist=loadfile    — все тесты одного файла в одном воркере.
# --dist=loadgroup   — тесты с одинаковой группой маркеров идут в один воркер.
# --dist=no          — не распределять, но воркеры всё равно запускаются (полезно
#                     для параллельного запуска одной и той же параметризации).
# --dist=each        — каждый воркер выполняет ВСЕ тесты, а не часть.
#                     Используется для повторения тестов на разных окружениях.

# Пример: тесты из одного файла не должны перемешиваться между воркерами
# pytest -n auto --dist=loadfile

# ---------------------------------------------------------------------------
# 40.3 Удалённые воркеры (--tx) и rsync
# ---------------------------------------------------------------------------
# Можно запускать тесты на других машинах через SSH.
# Для этого задаётся транспорт:
# --tx ssh=user@host//python=python3
# --tx popen//python=python3.8
# Для синхронизации файлов:
# --rsyncdir myproject

# Локальный пример (обычно не нужен): указание нескольких процессов с явным транспортом
# pytest -d --tx popen//python=python3 --tx popen//python=python3 -n 2

# ---------------------------------------------------------------------------
# 40.4 Особенности работы фикстур в xdist
# ---------------------------------------------------------------------------
# ВАЖНЕЙШИЙ МОМЕНТ: фикстуры с scope="session" выполняются ОДИН РАЗ НА КАЖДЫЙ ВОРКЕР,
# а не один раз на всю сессию! Если вам нужен единый ресурс для всех воркеров
# (например, общий временный каталог), используйте блокировки или внешний координатор.

# Пример: создание уникального временного каталога для воркера
@pytest.fixture(scope="session")
def worker_tmpdir(tmp_path_factory):
    # tmp_path_factory корректен в session-фикстуре с xdist
    dir = tmp_path_factory.mktemp(f"worker_{os.getpid()}")
    return dir

def test_write(worker_tmpdir):
    (worker_tmpdir / "file.txt").write_text("hello")
    assert True

