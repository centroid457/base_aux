# 40.6 Вывод в консоль (-s, -v) и параллельный запуск
# ---------------------------------------------------------------------------
# При использовании -n auto каждый воркер пишет в свой поток вывода.
# Чтобы видеть полный вывод, используйте -s:
# pytest -n auto -s

# Для упорядоченного вывода (сначала один воркер, потом другой) используйте
