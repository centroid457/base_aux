# 20. ПОВТОРНЫЙ ЗАПУСК ТЕСТОВ ПРИ ПАДЕНИИ (RETRY / FLAKY TESTS)
# =============================================================================
# Иногда тесты падают нестабильно (flaky) из-за сетевых задержек, гонок и т.д.
# Можно автоматически повторять упавший тест N раз перед тем, как признать его проваленным.
# Плагин pytest-rerunfailures даёт такой декоратор и консольный флаг.
# Установка: pip install pytest-rerunfailures

# ---------------------------------------------------------------------------
# 20.1 Декоратор @pytest.mark.flaky
# ---------------------------------------------------------------------------
# Повтор до 3 раз, с задержкой 1 секунда между попытками
@pytest.mark.flaky(reruns=3, reruns_delay=1)
def test_possibly_flaky():
    import random
    # Имитация: в 50% случаев падает
    assert random.random() > 0.5, "Временный сбой"

# В отчёте pytest:
# test_example.py::test_possibly_flaky RERUN
# test_example.py::test_possibly_flaky PASSED
# Если в итоге прошёл, то статус PASSED.
# Если все попытки провалились — FAILED.

# ---------------------------------------------------------------------------
# 20.2 Декоратор с условием повторения только для определённых исключений
# ---------------------------------------------------------------------------
@pytest.mark.flaky(reruns=2, reruns_delay=0.5, only_rerun="AssertionError")
def test_retry_on_assert():
    # Повторять только при AssertionError, другие ошибки сразу провалят тест
    assert False  # будет повторено 2 раза

# Также можно указать список: only_rerun=["AssertionError", "ValueError"]

# ---------------------------------------------------------------------------
# 20.3 Консольный эквивалент (без декоратора)
# ---------------------------------------------------------------------------
# Если нужно применить ко всем тестам или временно, можно через командную строку:
# pytest --reruns 3 --reruns-delay 1
# Это эквивалентно декоратору для каждого теста.

# ---------------------------------------------------------------------------
# 20.4 Как это выглядит в отчёте
# ---------------------------------------------------------------------------
# При использовании -v (verbose) в выводе вы увидите:
# test_file.py::test_func RERUN
# test_file.py::test_func RERUN
# test_file.py::test_func PASSED
#
# В сокращённом выводе и JUnit-отчёте итог будет PASSED,
# но количество rerun’ов можно увидеть в консоли.
# Для CI/CD можно использовать --junitxml с дополнительными свойствами rerun.

# ---------------------------------------------------------------------------
# 20.5 Важные нюансы и частые ошибки
# ---------------------------------------------------------------------------
# - Не злоупотребляйте: flaky-тесты скрывают реальные баги. Лучше исправлять корень проблемы.
# - Если тест использует случайные данные, повтор может пройти случайно. Фиксируйте seed.
# - При использовании с pytest-xdist (параллельный запуск) reruns работает корректно.
# - Комбинация с @pytest.mark.dependency: если зависимый тест перезапущен и в итоге прошёл,
#   следующий тест будет выполнен (зависимость удовлетворена).
# - Сочетание с @pytest.mark.xfail: если flaky-тест помечен как xfail, повторные попытки
#   не выполняются — он сразу считается XFAIL.
# - Плагин ловит исключения только из тела теста; ошибки в фикстурах не перезапускаются.
#   Для перезапуска фикстур используйте scope='function' и перезапуск всего теста.





