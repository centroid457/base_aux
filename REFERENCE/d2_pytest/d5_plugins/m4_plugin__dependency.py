# ======================================================================================================================
# 19. PYTEST-DEPENDENCY: ЗАВИСИМОСТИ МЕЖДУ ТЕСТАМИ
# =============================================================================
# Плагин позволяет пропускать тест, если тест, от которого он зависит,
# упал или был пропущен. Альтернатива глобальным переменным и ручным skip.
# Установка: pip install pytest-dependency
import pytest


# ---------------------------------------------------------------------------
# ВАЖНО
# МИНУСЫ
# 1=при запуске индивидуально/напрямую зависимых тестов - зависимый тест считается НЕПРОШЕДШИМ!!!
# и тогда текущий будет пропущен!!!

# РЕШЕНИЕ
# 1=ФИКСТУРА на результат особенно если это простая проверка.


# =============================================================================
# ---------------------------------------------------------------------------
# 19.1 Базовая зависимость: depends=["имя тестовой функции"]
# ---------------------------------------------------------------------------
@pytest.mark.dependency()
def test_login():
    # Предусловие: успешный логин
    assert True

@pytest.mark.dependency(depends=["test_login"])
def test_profile_access():
    # Этот тест будет пропущен, если test_login упал или был пропущен
    assert True

# ---------------------------------------------------------------------------
# 19.2 Именованные зависимости (рекомендуется)
# ---------------------------------------------------------------------------
# Если имена функций меняются или совпадают в разных файлах,
# лучше задать явное имя через маркер dependency(name="...")

@pytest.mark.dependency(name="auth")
def test_authentication():
    assert True

@pytest.mark.dependency(name="db_ready")
def test_database_setup():
    assert True

@pytest.mark.dependency(depends=["auth", "db_ready"])
def test_full_flow():
    assert True

