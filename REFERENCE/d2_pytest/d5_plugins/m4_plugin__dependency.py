# ---------------------------------------------------------------------------
# 19.3 Зависимости между классами и модулями
# ---------------------------------------------------------------------------
# По умолчанию ищется по полному nodeid (путь::класс::метод).
# Можно ссылаться на тесты из других классов/файлов.

class TestAPI:
    @pytest.mark.dependency(name="api_health")
    def test_health(self):
        assert True

class TestFrontend:
    @pytest.mark.dependency(depends=["api_health"])
    def test_ui_loads(self):
        assert True

# Или по полному пути (если имена не уникальны):
# depends=["test_file.py::test_func", "TestClass::test_method"]

# ---------------------------------------------------------------------------
# 19.4 Что происходит при падении/пропуске зависимости
# ---------------------------------------------------------------------------
# Если зависимость FAILED – зависимый тест SKIPPED
# Если зависимость SKIPPED – зависимый тест SKIPPED
# Если зависимость XFAIL (ожидаемо упала) – зависимый тест выполнится (зависимость удовлетворена)
# Если зависимость XPASS (неожиданно прошла) – зависимый тест SKIPPED

@pytest.mark.dependency(name="xfail_dep")
@pytest.mark.xfail(reason="известный баг")
def test_xfail_dep():
    assert False  # xfail, значит зависимость выполнена

@pytest.mark.dependency(depends=["xfail_dep"])
def test_dependent_on_xfail():
    # Этот тест выполнится, несмотря на xfail в зависимости
    assert True

# ---------------------------------------------------------------------------
# 19.5 Зависимости с параметризацией
# ---------------------------------------------------------------------------
# Параметризованный тест генерирует несколько nodeid. Нужно указывать
# параметры в имени зависимости или давать уникальное имя каждому варианту.

@pytest.mark.parametrize("x", [1, 2], ids=["one", "two"])
@pytest.mark.dependency(name="param_test")
def test_parametrized(x):
    assert x > 0

# Чтобы зависеть от конкретной параметризации, нужно знать nodeid.
# Лучше задать уникальные имена через параметризацию ids и использовать их.
# Пример явного имени через mark.dependency с параметризацией (чуть сложнее):
@pytest.mark.parametrize("user_id, expected", [
    pytest.param(1, "Alice", id="alice"),
    pytest.param(2, "Bob", id="bob")
])
@pytest.mark.dependency(name="user_check")
def test_user_check(user_id, expected):
    pass

# Тогда можно зависеть: depends=["user_check[alice]"]

# Альтернативно, можно не использовать dependency на параметризованные тесты,
# а положиться на общий предусловительный тест.

# ---------------------------------------------------------------------------
# 19.6 Групповые зависимости: scope
# ---------------------------------------------------------------------------
# scope="session" (по умолчанию) – зависимости видны в рамках всей сессии.
# scope="module" – только внутри текущего модуля.
# scope="class" – только внутри класса.

# module scope позволяет переиспользовать имена в разных файлах без конфликтов.

@pytest.mark.dependency(name="module_setup", scope="module")
def test_module_prereq():
    assert True

@pytest.mark.dependency(depends=["module_setup"], scope="module")
def test_after_module_setup():
    assert True

# ---------------------------------------------------------------------------
# 19.7 Смешанное использование с другими фикстурами
# ---------------------------------------------------------------------------
# Фикстуры и dependency прекрасно сочетаются.
@pytest.fixture
def db():
    return "connected"

@pytest.mark.dependency(name="with_fixture")
def test_using_db(db):
    assert db == "connected"

@pytest.mark.dependency(depends=["with_fixture"])
def test_another(db):
    assert db == "connected"

# ---------------------------------------------------------------------------
# 19.8 ЧАСТЫЕ ОШИБКИ И ВАЖНЫЕ МОМЕНТЫ
# ---------------------------------------------------------------------------
# 1. Тест, на который ссылается depends, должен быть выполнен раньше.
#    Порядок определяется порядком в файле/классе, если не используется random-order.
#    Если зависимость объявлена, но ещё не выполнена – тест будет SKIPPED.

# 2. Несуществующая зависимость: если имя в depends не найдено, тест получит статус SKIPPED,
#    а в выводе будет предупреждение. Всегда проверяйте имена.

# 3. При использовании pytest-xdist параллельно зависимости не работают корректно,
#    потому что тесты могут выполняться в разных процессах. Плагин не поддерживает
#    межпроцессные зависимости. Для параллельного запуска используйте --dist=loadscope.

# 4. Dependency не заменяет setup/teardown фикстур! Если нужно просто подготовить
#    окружение – используйте фикстуры, а не зависимости. Зависимости – для проверки
#    логики: "тест Б имеет смысл только если тест А пройден".

# 5. Если тест-зависимость сам пропущен через pytest.mark.skip, он считается SKIPPED,
#    и все зависящие от него тесты тоже будут пропущены.

# 6. Можно комбинировать dependency с другими маркерами (например, xfail, parametrize),
#    но порядок маркеров не важен.

# 7. Имена зависимостей чувствительны к регистру и точному совпадению.

# 8. Если один тест помечен как dependency, но на него никто не ссылается – ничего не меняется.

# 9. Зависимость работает для тестов, сгенерированных через параметризацию.
#    Но нужно ссылаться на точный nodeid: например, test_user_check[alice].
#    Полный список nodeid можно увидеть: pytest --collect-only -q

