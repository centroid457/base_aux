# 39. PYTEST-ORDERING: УПРАВЛЕНИЕ ПОРЯДКОМ ВЫПОЛНЕНИЯ ТЕСТОВ
# =============================================================================
# Плагин pytest-ordering позволяет задавать порядок выполнения тестов
# внутри одного модуля или класса с помощью декоратора @pytest.mark.order.
# Установка: pip install pytest-ordering

import pytest

# ---------------------------------------------------------------------------
# 39.1 Базовое использование: абсолютный порядок
# ---------------------------------------------------------------------------

@pytest.mark.order(2)
def test_second():
    assert True

@pytest.mark.order(1)
def test_first():
    # Выполнится раньше, чем test_second, несмотря на расположение в коде
    assert True

# Если у нескольких тестов одинаковый индекс, порядок между ними не гарантирован.

# ---------------------------------------------------------------------------
# 39.2 Относительный порядок: раньше/позже другого теста
# ---------------------------------------------------------------------------

@pytest.mark.order(after="test_first")
def test_after_first():
    # Выполнится после test_first
    assert True

@pytest.mark.order(before="test_second")
def test_before_second():
    # Выполнится перед test_second
    assert True

# Можно указывать несколько зависимостей:
# @pytest.mark.order(after=["test_a", "test_b"])

# ---------------------------------------------------------------------------
# 39.3 Упорядочивание методов внутри классов
# ---------------------------------------------------------------------------

class TestOrdered:
    @pytest.mark.order(2)
    def test_middle(self):
        pass

    @pytest.mark.order(1)
    def test_start(self):
        pass

    @pytest.mark.order(after="test_middle")
    def test_end(self):
        pass

# ---------------------------------------------------------------------------
# 39.4 Пропуск сортировки: оставить порядок как в исходном коде
# ---------------------------------------------------------------------------
# По умолчанию pytest-ordering сортирует тесты по индексам. Если нужно
# сохранить порядок, заданный в файле, используйте отрицательные индексы
# или отключите плагин для конкретного теста маркером @pytest.mark.order(-1)
# либо не используйте маркер вообще.
# @pytest.mark.order(-1) означает "в конец".

# ---------------------------------------------------------------------------
# 39.5 Взаимодействие с другими плагинами и особенности
# ---------------------------------------------------------------------------
# - При использовании xdist порядок соблюдается только внутри одного процесса
#   (на уровне модуля). Глобальный порядок не гарантируется.
# - Не рекомендуется чрезмерно полагаться на порядок — тесты должны быть
#   независимыми. Используйте ordering только для случаев, когда иначе нельзя
#   (например, тестирование GUI с последовательными шагами).
# - Если тест пропущен (skip/xfail), маркер order всё равно учитывается,
#   и следующие по порядку могут выполниться после пропущенного (если это
#   относительный after).


