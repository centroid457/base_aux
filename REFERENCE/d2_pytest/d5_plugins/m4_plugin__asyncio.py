# 42. PYTEST-ASYNCIO: ТЕСТИРОВАНИЕ АСИНХРОННОГО КОДА
# =============================================================================
# Плагин pytest-asyncio позволяет писать и запускать асинхронные тесты
# (async def) и использовать asyncio-фикстуры.
# Установка: pip install pytest-asyncio


# ---------------------------------------------------------------------------
# 42.8 Частые ошибки и важные замечания
# ---------------------------------------------------------------------------
# 1. Запуск асинхронного кода в синхронном тесте без маркера – ошибка
#    RuntimeError. Используйте @pytest.mark.asyncio или asyncio_mode = auto.
# 2. Использование time.sleep внутри асинхронных тестов – блокирует event loop.
#    Всегда используйте asyncio.sleep.
# 3. Изменение event loop во время тестирования – опасно. Лучше позволить
#    плагину управлять loop.
# 4. СОВМЕСТНЫЙ запуск синхронных и асинхронных тестов с asyncio_mode=strict
#    требует, чтобы синхронные тесты не содержали async def.
# 5. Если тест запускается через pytest -s, и в нём есть print после await,
#    вывод может буферизоваться – используйте flush=True или настройки PyCharm.
# 6. При использовании session-фикстур с asyncio помните, что event loop
#    живёт только во время теста, поэтому нельзя запускать await вне тестов.


# ---------------------------------------------------------------------------
import asyncio
import pytest


# ---------------------------------------------------------------------------
# 42.1 асинхронные ТЕСТОВЫЕ ФУНКЦИИ
# ---------------------------------------------------------------------------
async def test_async_basic():
    result = await asyncio.sleep(0.1, result=42)
    assert result == 42

# pytest-asyncio автоматически подхватывает async def тесты.
# По умолчанию (с версии 0.17) тесты используют один и тот же event loop.

# ---------------------------------------------------------------------------
# 42.2 Режимы работы event loop
# ---------------------------------------------------------------------------
# pytest-asyncio поддерживает несколько режимов, задаваемых через pytest.ini
# или маркер @pytest.mark.asyncio:
#
# mode="auto"    (по умолчанию) — сам определяет, нужен ли отдельный loop.
# mode="strict"  — только для тестов, явно помеченных @pytest.mark.asyncio.
#                Позволяет избежать случайного запуска async-функций в синхронном контексте.
#
# В pytest.ini:
# [pytest]
# asyncio_mode = strict

# Рекомендуется использовать strict, чтобы явно указывать, какие тесты асинхронные.

@pytest.mark.asyncio
async def test_with_strict_mode():
    await asyncio.sleep(0)
    assert True

# ---------------------------------------------------------------------------
# 42.3 Асинхронные ФИКСТУРЫ - без маркера
# ---------------------------------------------------------------------------
# Фикстуры могут быть асинхронными и использовать await.

@pytest.fixture     # не указывается маркер asyncio!
async def async_fixt1():
    """Асинхронная фикстура"""
    await asyncio.sleep(0.1)
    return {"key": "value"}

@pytest.mark.asyncio    # маркер ставится только на тестовой функции!!!
async def test_using_async_fixture(async_fixt1):
    assert async_fixt1["key"] == "value"

# Важно: асинхронные фикстуры с областью видимости (scope) работают,
# но при использовании сессионных фикстур с event loop нужно быть осторожным.


# ---------------------------------------------------------------------------
# 42.4 ПАРАМЕТРИЗАЦИЯ и циклы событий
# ---------------------------------------------------------------------------
# Параметризованные асинхронные тесты - работают как обычно.

@pytest.mark.parametrize("x,y,expected", [(1, 2, 3), (10, 20, 30)])
@pytest.mark.asyncio
async def test_async_add(x, y, expected):
    await asyncio.sleep(0)
    assert x + y == expected

# ---------------------------------------------------------------------------
# 42.5 Совместное использование с ДРУГИМИ ПЛАГИНАМИ
# ---------------------------------------------------------------------------
# - pytest-xdist: асинхронные тесты работают в параллельных процессах,
#   каждый со своим event loop. Конфликтов не возникает.
# - pytest-timeout: таймаут применяется корректно, прерывая ожидание.
# - pytest-html / json-report: результаты отображаются как обычно.

# ---------------------------------------------------------------------------
# 42.6 Тестирование таймаутов и исключений (asyncio.wait_for)
# ---------------------------------------------------------------------------
@pytest.mark.asyncio
async def test_timeout():
    """Тест демонстрирует использование asyncio.wait_for."""
    async def slow_task():
        await asyncio.sleep(5)
        return "done"
    with pytest.raises(asyncio.TimeoutError):
        await asyncio.wait_for(slow_task(), timeout=0.1)

# ---------------------------------------------------------------------------
# 42.7 Переопределение event loop (scope="session")
# ---------------------------------------------------------------------------
# Если нужно использовать один event loop на всю сессию, можно объявить фикстуру:
@pytest.fixture(scope="session")
def event_loop():
    """Создаём сессионный event loop (доступен в conftest.py)."""
    loop = asyncio.new_event_loop()
    yield loop
    loop.close()

# Однако pytest-asyncio часто управляет loop самостоятельно, и такой override
# нужен только для особых случаев, например, при использовании uvloop.


