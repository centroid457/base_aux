def show_representations(data: bytes):
    """
    МАКСИМАЛЬНО НАГЛЯДНОЕ ПРЕДСТАВЛЕНИЕ БАЙТОВ
    Для отладки UART пакетов, RFID меток, датчиков
    """

    # ========================================================================
    # 1. БАЗОВЫЕ ПРЕДСТАВЛЕНИЯ (ваши оригинальные + дополнения)
    # ========================================================================
    print("=" * 100)
    print(f"📦 БАЙТОВЫЙ ДАМП: {len(data)} байт")
    print("-" * 100)

    print(f"BYTES (raw)   : {data}")
    print(f"BYTES (repr)  : {repr(data)}")
    print(f"DEC           : {':'.join(f'{b:3d}' for b in data)}")
    print(f"HEX (0x)      : {':'.join(f'0x{b:02X}' for b in data)}")
    print(f"HEX (clean)   : {':'.join(f'{b:02X}' for b in data)}")
    print(f"BIN (0b)      : {':'.join(f'0b{b:08b}' for b in data)}")
    print(f"BIN (clean)   : {':'.join(f'{b:08b}' for b in data)}")
    print(f"CHR (visual)  : {':'.join(chr(b) if 32 <= b < 127 else f'[{b:02X}]' for b in data)}")
    print(f"STR (joined)  : \"{''.join(chr(b) if 32 <= b < 127 else '.' for b in data)}\"")

    # ========================================================================
    # 2. НОВОЕ: ГРУППИРОВКА ПО БИТАМ (для парсинга флагов)
    # ========================================================================
    print(f"\n🎯 БИТОВЫЕ ПОЛЯ (каждый бит отдельно):")
    for i, b in enumerate(data):
        bits = f"{b:08b}"
        # Показываем позиции битов: 7 6 5 4 3 2 1 0
        bit_positions = " ".join(f"[{7 - j}]{bits[j]}" for j in range(8))
        print(f"  Byte[{i}] = 0x{b:02X} -> {bit_positions}")
        # Показываем какие биты установлены
        set_bits = [j for j in range(8) if (b >> (7 - j)) & 1]
        print(f"           -> Установлены биты: {set_bits if set_bits else 'нет'}")

    # ========================================================================
    # 3. НОВОЕ: ИНТЕРПРЕТАЦИЯ КАК ЧИСЛА (разные форматы)
    # ========================================================================
    print(f"\n🔢 ИНТЕРПРЕТАЦИЯ КАК ЧИСЛА:")

    # Как одиночные байты
    if len(data) == 1:
        print(f"  Unsigned byte:  {data[0]}")
        print(f"  Signed byte:    {data[0] if data[0] < 128 else data[0] - 256}")

    # Как 16-битные целые
    if len(data) >= 2:
        for offset in range(0, len(data) - 1, 2):
            chunk = data[offset:offset + 2]
            if len(chunk) == 2:
                be = int.from_bytes(chunk, 'big')
                le = int.from_bytes(chunk, 'little')
                print(f"  Bytes[{offset}:{offset + 2}] = {chunk.hex(':')}")
                print(f"    uint16 BE: {be:5d}  LE: {le:5d}")
                print(
                    f"    int16  BE: {be if be < 32768 else be - 65536:5d}  LE: {le if le < 32768 else le - 65536:5d}")

    # Как 32-битное целое
    if len(data) >= 4:
        chunk_be = data[:4]
        chunk_le = data[-4:] if len(data) >= 8 else data[:4]
        print(f"  uint32 BE: {int.from_bytes(chunk_be, 'big'):10d}  (0x{chunk_be.hex().upper()})")
        print(f"  int32  BE: {int.from_bytes(chunk_be, 'big', signed=True):10d}")

    # Как float (если ровно 4 байта)
    if len(data) == 4:
        import struct
        try:
            float_be = struct.unpack('>f', data)[0]
            float_le = struct.unpack('<f', data)[0]
            print(f"  float32 BE: {float_be:.6f}")
            print(f"  float32 LE: {float_le:.6f}")
        except:
            pass

    # ========================================================================
    # 4. НОВОЕ: АНАЛИЗ СТРУКТУРЫ ПАКЕТА (поиск заголовков)
    # ========================================================================
    print(f"\n📋 АНАЛИЗ СТРУКТУРЫ ПАКЕТА:")

    # Частые заголовки протоколов
    protocol_markers = {
        b'\xAA': "Возможный START байт (RFID/датчики)",
        b'\x55': "Возможный END байт",
        b'\x7E': "HDLC флаг",
        b'AT': "AT-команда",
        b'$G': "NMEA (GPS)",
        b'\x02': "STX (Start of Text)",
        b'\x03': "ETX (End of Text)",
        b'\x0D\x0A': "CRLF (конец строки)",
        b'\x00\x00': "Padding/нулевые байты",
    }

    data_str = data
    for marker, desc in protocol_markers.items():
        pos = data_str.find(marker)
        if pos != -1:
            print(f"  ✓ Найден \"{desc}\" на позиции {pos}")

    # ========================================================================
    # 5. НОВОЕ: СТАТИСТИКА ПО БАЙТАМ
    # ========================================================================
    print(f"\n📊 СТАТИСТИКА:")

    printable_count = sum(1 for b in data if 32 <= b < 127)
    null_count = data.count(0)
    ff_count = data.count(0xFF)

    print(f"  Печатных ASCII: {printable_count}/{len(data)} ({printable_count * 100 // len(data)}%)")
    print(f"  Нулевых байтов: {null_count}")
    print(f"  Байтов 0xFF:    {ff_count}")

    # Минимальный/максимальный байт
    if data:
        print(f"  Min byte: 0x{min(data):02X} ({min(data)})")
        print(f"  Max byte: 0x{max(data):02X} ({max(data)})")

    # ========================================================================
    # 6. НОВОЕ: АЛЬТЕРНАТИВНЫЕ КОДИРОВКИ (для текстовых данных)
    # ========================================================================
    if printable_count > len(data) * 0.7:  # Если больше 70% печатных
        print(f"\n🌍 ТЕКСТОВЫЕ ИНТЕРПРЕТАЦИИ:")
        for encoding in ['ascii', 'utf-8', 'cp1251', 'latin-1']:
            try:
                decoded = data.decode(encoding)
                if decoded.isprintable():
                    print(f"  {encoding:8s}: \"{decoded.strip()}\"")
            except:
                pass

    # ========================================================================
    # 7. НОВОЕ: ЦВЕТОВОЕ ВЫДЕЛЕНИЕ БАЙТОВ (если терминал поддерживает)
    # ========================================================================
    # Цветовая карта байтов - визуально видны структуры: ASCII зелёные, управляющие жёлтые, нули серые - глазом можно заметить паттерны
    print(f"\n🎨 ВИЗУАЛЬНАЯ КАРТА БАЙТОВ:")
    for i, b in enumerate(data):
        if b == 0x00:
            color = "\033[90m"  # Серый для нулей
        elif b == 0xFF:
            color = "\033[91m"  # Красный для 0xFF
        elif 32 <= b < 127:
            color = "\033[92m"  # Зелёный для ASCII
        elif b < 0x20:
            color = "\033[93m"  # Жёлтый для управляющих
        else:
            color = "\033[94m"  # Синий для остальных
        reset = "\033[0m"
        print(f"  {color}[{i:2d}] 0x{b:02X}{reset}", end="")
        if (i + 1) % 8 == 0:
            print()  # Перенос каждые 8 байт
    if len(data) % 8 != 0:
        print()

    # ========================================================================
    # 8. НОВОЕ: СГЕНЕРИРОВАННЫЙ КОД ДЛЯ ВОСПРОИЗВЕДЕНИЯ
    # ========================================================================
    print(f"\n⚡ КОД ДЛЯ ВОСПРОИЗВЕДЕНИЯ:")
    print(f"  # Скопируйте для тестирования:")
    print(f"  data = bytes.fromhex('{data.hex().upper()}')")
    print(f"  # или")
    print(f"  data = {list(data)}")

    print("=" * 70 + "\n")


