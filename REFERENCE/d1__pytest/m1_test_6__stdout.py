import sys
import time


# ======================================================================================================================
# =============================================================================
# 22. ВЫВОД PRINT В РЕАЛЬНОМ ВРЕМЕНИ В PYCHARM
# =============================================================================
# Проблема: при запуске тестов из PyCharm весь вывод (print, stdout) буферизируется
# и появляется только после завершения теста. Во время выполнения теста консоль пуста,
# что неудобно для отладки, особенно при работе с потоками, чтении буферов и т.д.

# Решение: отключить захват вывода pytest и заставить Python/PyCharm сбрасывать буфер.
# Ниже несколько способов — выберите подходящий.

# ---------------------------------------------------------------------------
# 22.1 ФЛАГ -s (или --capture=no) в pytest
# ---------------------------------------------------------------------------
# Запуск pytest с флагом -s отключает захват stdout/stderr.
# В PyCharm это можно сделать глобально для конфигурации запуска:
#   1. Откройте Run -> Edit Configurations...
#   2. Найдите вашу конфигурацию pytest (или создайте новую).
#   3. В поле "Additional Arguments" добавьте: -s
#   4. Примените и запускайте тесты — весь вывод будет немедленно виден.

# Команда в терминале:
# pytest -s

# Для большего контроля:
# pytest --capture=no             # полностью отключает перехват
# pytest --capture=tee-sys        # выводит и в консоль, и в перехваченные буферы

# ---------------------------------------------------------------------------
# 22.2 ПРИНУДИТЕЛЬНЫЙ СБРОС БУФЕРА В САМОМ КОДЕ
# ---------------------------------------------------------------------------
# Даже с -s Python может буферизировать вывод, если консоль не терминал.
# В PyCharm встроенная консоль эмулирует терминал, но не всегда.
# Простейший фикс — использовать print с flush=True:
def test_print_realtime():
    for i in range(5):
        print(f"Шаг {i}", flush=True)
        time.sleep(0.5)

# Либо принудительно вызывать sys.stdout.flush() после каждого print.
# Важно: не забывайте про flush в многопоточных/многопроцессных тестах.

# ---------------------------------------------------------------------------
# 22.3 НАСТРОЙКА PYCHARM: "EMULATE TERMINAL IN OUTPUT CONSOLE"
# ---------------------------------------------------------------------------
# В PyCharm можно включить эмуляцию терминала для конфигурации запуска:
#   1. Run -> Edit Configurations
#   2. Выберите вашу pytest-конфигурацию
#   3. Поставьте галочку "Emulate terminal in output console"
#      (находится в разделе "Execution" или "Logs", зависит от версии PyCharm)
#   4. Это часто решает проблему буферизации без дополнительных флагов.
# При этом -s может и не понадобиться.

# ---------------------------------------------------------------------------
# 22.4 ИСПОЛЬЗОВАНИЕ LOGGING С МГНОВЕННЫМ ВЫВОДОМ
# ---------------------------------------------------------------------------
# Для серьёзных проектов лучше использовать модуль logging с настроенным обработчиком:
import logging
logging.basicConfig(level=logging.INFO, format='%(asctime)s - %(message)s',
                    stream=sys.stdout, force=True)
# force=True заставляет переопределить корневой логгер (полезно при запуске из pytest).

def test_with_logging(caplog):
    for i in range(3):
        logging.info(f"Обработка {i}")
        time.sleep(0.5)
    # Логи будут появляться сразу, если обработчик пишет в терминал.
    # caplog также будет перехватывать логи для тестов.

# ---------------------------------------------------------------------------
# 22.5 ИСПОЛЬЗОВАНИЕ PYTEST HOOK ДЛЯ АВТОМАТИЧЕСКОГО FLUSH
# ---------------------------------------------------------------------------
# Можно написать фикстуру или хук, который заставит Python не буферизировать вывод.
# Например, установить переменную окружения PYTHONUNBUFFERED=1.
# В PyCharm это можно добавить в "Environment variables" конфигурации:
#   PYTHONUNBUFFERED=1
# Это отключает буферизацию stdout/stderr на уровне интерпретатора.

# В pytest.ini тоже можно задать:
# [pytest]
# addopts = -s

# ---------------------------------------------------------------------------
# 22.6 ЧТО ДЕЛАТЬ, ЕСЛИ ВЫ ИСПОЛЬЗУЕТЕ ПАРАЛЛЕЛЬНЫЙ ЗАПУСК (pytest-xdist)?
# ---------------------------------------------------------------------------
# При параллельном запуске вывод каждого процесса идёт в свой поток,
# и PyCharm может буферизировать каждый поток отдельно. Рекомендуется:
#   pytest -n auto -s
# и дополнительно в коде использовать print(..., flush=True).
# Иногда помогает отключить буферизацию процессов через переменную PYTHONUNBUFFERED=1
# (можно задать в Environment variables конфигурации).

# =============================================================================
# КРАТКИЙ РЕЦЕПТ ДЛЯ PYCHARM
# =============================================================================
# 1. В Edit Configurations -> Additional Arguments добавьте: -s
# 2. Поставьте галочку "Emulate terminal in output console"
# 3. В Environment variables добавьте: PYTHONUNBUFFERED=1
# 4. В коде используйте print(..., flush=True) или logging.
# После этого весь вывод будет виден в реальном времени.


