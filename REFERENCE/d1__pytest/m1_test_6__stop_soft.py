# 45.2 Остановка во время длинного асинхронного теста (отмена задачи)
# ---------------------------------------------------------------------------
# Для асинхронных тестов (@pytest.mark.asyncio) можно использовать
# механизм отмены asyncio.Task. Каждый тест выполняется как отдельная
# задача. FastAPI может хранить ссылки на запущенные задачи и вызывать
# .cancel() для их прерывания.
# Внутри теста нужно обрабатывать asyncio.CancelledError для выполнения
# очистки (закрытие портов, выключение питания).

import asyncio
import pytest

# Хранилище активных задач (в реальном коде – например, глобальный словарь)
active_tasks = {}

@pytest.hookimpl(tryfirst=True)
def pytest_runtest_call(item):
    """Оборачиваем выполнение асинхронного теста в задачу с возможностью отмены."""
    if item.get_closest_marker("asyncio"):
        async def run():
            # Здесь вызывается тело теста, pytest-asyncio сам запустит event loop
            pass
        # Это упрощённый пример; реальное внедрение сложнее и требует
        # интеграции с pytest-asyncio на уровне event loop.
        pass

# Более практичный подход: использовать фикстуру, которая создаёт
# asyncio.Task для теста и сохраняет его в контексте, а при отмене
# вызывает task.cancel().

@pytest.fixture
async def test_task(request):
    """Фикстура, создающая задачу и позволяющая отменить её извне."""
    task = asyncio.current_task()
    request.node._test_task = task  # сохраняем в узле теста
    yield
    # очистка, если нужно

# Тогда в FastAPI можно найти нужный task и вызвать task.cancel().
# Тест должен периодически проверять отмену: await asyncio.sleep(0) или
# явно обрабатывать CancelledError внутри while-циклов.

@pytest.mark.asyncio
async def test_long_operation():
    try:
        for i in range(1000):
            # делаем какую-то работу
            await asyncio.sleep(0.1)  # позволяет переключиться и обработать отмену
            # проверка на отмену: if asyncio.current_task().cancelled(): ...
    except asyncio.CancelledError:
        # Здесь выполняем необходимый teardown
        print("Тест отменён, освобождаем ресурсы")
        raise  # переподнимаем, чтобы pytest зафиксировал отмену

