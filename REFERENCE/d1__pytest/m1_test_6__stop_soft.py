# Требуется два уровня остановки:
#   1) Между тестами – с гарантированным teardown.
#   2) Во время выполнения длинного теста – с максимальным сохранением очистки.

# ---------------------------------------------------------------------------
# 45.1 Остановка между тестами (проверка флага)
# ---------------------------------------------------------------------------
# Используем глобальный флаг, который FastAPI может изменять, и фикстуру
# с autouse, проверяющую этот флаг перед стартом каждого теста.
# При установке флага текущий тест завершается (pytest.exit), все
# последующие пропускаются, фикстуры корректно завершают ресурсы.

import pytest
