import os
import tempfile

# Файл-триггер для остановки
STOP_FILE = os.path.join(tempfile.gettempdir(), "pytest_stop.flag")

@pytest.fixture(autouse=True)
def check_stop_flag():
    """Фикстура, проверяющая флаг остановки перед каждым тестом."""
    if os.path.exists(STOP_FILE):
        os.remove(STOP_FILE)  # очищаем флаг
        pytest.exit("Остановка по внешнему запросу", returncode=0)
    yield

# Теперь создание файла pytest_stop.flag в TEMP-директории вызовет
# корректную остановку после завершения текущего теста с teardown.
# Это полностью безопасно: все фикстуры отработают до конца.

# ---------------------------------------------------------------------------
# 44.5 ОБЁРТКА ДЛЯ ВСЕХ TEARDOWN: pytest.fixture с always-очисткой
# ---------------------------------------------------------------------------
# Чтобы гарантировать очистку даже при прерывании внутри теста,
# используйте конструкцию try/finally в фикстуре или тесте.
# Но лучший способ — размещать код очистки в фикстуре после yield,
# pytest САМ вызывает его при любом завершении теста (кроме kill -9).

@pytest.fixture
def uart_device():
    """Фикстура, гарантированно закрывающая порт."""
    port = open("/dev/ttyUSB0", "rb+")  # имитация
    try:
        yield port
    finally:
        # Этот код выполнится даже при падении теста,
        # пропуске (skip) или штатном завершении
        port.close()

def test_uart_read(uart_device):
    data = uart_device.read(10)
    assert len(data) == 10

