# не выключить питание и т.д.

# ---------------------------------------------------------------------------
# 44.1 ВСТРОЕННЫЙ МЕХАНИЗМ: pytest -x и --maxfail
# ---------------------------------------------------------------------------
# pytest -x           # остановиться после первого падения (teardown выполняется)
# pytest --maxfail=3  # остановиться после трёх падений (teardown выполняется)
# Эти варианты полностью безопасны — все фикстуры корректно завершаются,
# потому что pytest сам управляет остановкой между тестами.

# ---------------------------------------------------------------------------
# 44.2 СИГНАЛ SIGTERM: мягкое завершение (вместо Ctrl+C)
# ---------------------------------------------------------------------------
# На Linux/Mac: отправка SIGTERM (kill <pid>) заставляет pytest завершить
# ТЕКУЩИЙ тест, выполнить его teardown и остановиться.
# В отличие от Ctrl+C (SIGINT), который вызывает немедленное исключение,
# SIGTERM обрабатывается более аккуратно.
# На Windows сигналы работают не так хорошо, но можно использовать
# taskkill /T /PID <pid> (с флагом /T убивает всё дерево, teardown может не успеть).

