# 45.3 Остановка синхронного длинного теста (потоки и исключения)
# ---------------------------------------------------------------------------
# Синхронный код, заблокированный в time.sleep() или в вызове C-функции,
# нельзя безопасно прервать извне без риска оставить ресурсы в грязном состоянии.
# Возможные подходы:
#   а) Переписать тест на асинхронный (предпочтительно).
#   б) Запускать каждый тест в отдельном потоке и пытаться принудительно
#      остановить его через ctypes.pythonapi.PyThreadState_SetAsyncExc,
#      что может привести к краху интерпретатора или блокировкам.
#   в) Использовать subprocess для изоляции теста: при остановке завершать
#      процесс целиком, но тогда teardown не выполнится. Компенсировать
#      внешним скриптом сброса оборудования.

# Для чувствительного оборудования это неприемлемо, поэтому настоятельно
# рекомендуется делать длительные тесты асинхронными с возможностью отмены.

