# ======================================================================================================================
import pytest
import time

# =============================================================================
# 36. PYTEST-TIMEOUT: ОГРАНИЧЕНИЕ ВРЕМЕНИ ВЫПОЛНЕНИЯ ТЕСТОВ
# =============================================================================
# Плагин pytest-timeout позволяет задать максимальную длительность теста
# и автоматически провалить его, если он превысил лимит.
# Установка: pip install pytest-timeout

# ---------------------------------------------------------------------------
# 36.1 Базовое использование: декоратор @pytest.mark.timeout
# ---------------------------------------------------------------------------

@pytest.mark.timeout(5)  # 5 секунд
def test_quick_enough():
    time.sleep(2)  # пройдёт
    assert True

# Тест, который гарантированно превысит таймаут (раскомментируйте для проверки):
# @pytest.mark.timeout(1)
# def test_too_slow():
#     time.sleep(3)  # упадёт с TimeoutError

# ---------------------------------------------------------------------------
# 36.2 Глобальный таймаут через командную строку
# ---------------------------------------------------------------------------
# Можно задать лимит для всех тестов сразу (перекрывается декораторами):
# pytest --timeout=10

# Для разных типов тестов:
# pytest --timeout=60       # глобально 60 секунд
# pytest --timeout=0        # отключить таймаут (значение по умолчанию)

# Значение по умолчанию также можно прописать в pytest.ini:
# [pytest]
# timeout = 30

# ---------------------------------------------------------------------------
# 36.3 Методы прерывания: signal и thread
# ---------------------------------------------------------------------------
# Плагин использует два способа остановки теста:

# 1) Метод 'signal' (по умолчанию на Unix-системах):
#    Отправляет SIGALRM тестовому процессу. Быстро и надёжно, но не работает
#    на Windows и несовместим с некоторыми библиотеками (например, некоторыми C-расширениями).
#    Задать явно: @pytest.mark.timeout(5, method='signal')

# 2) Метод 'thread' (по умолчанию на Windows, универсален):
#    Создаёт отдельный поток-наблюдатель, который вызывает исключение в главном потоке.
#    Работает везде, но может не прервать тест, если он заблокирован в C-коде без GIL.
#    Задать явно: @pytest.mark.timeout(5, method='thread')

@pytest.mark.timeout(2, method='thread')
def test_thread_timeout():
    for i in range(10):
        time.sleep(0.5)
    assert True

# Если в вашем проекте тесты часто зависают в системных вызовах,
# метод 'thread' может не справиться. В таких случаях лучше использовать
# внешний мониторинг (например, через subprocess с таймаутом).

# ---------------------------------------------------------------------------
# 36.4 Таймаут для фикстур
# ---------------------------------------------------------------------------
# По умолчанию таймаут применяется только к телу теста, но не к фикстурам.
# Чтобы контролировать время выполнения фикстур, используйте параметр 'func_only=False':

@pytest.fixture(scope="module")
def heavy_resource():
    # Имитация долгой инициализации
    time.sleep(4)
    return "resource"

@pytest.mark.timeout(5, func_only=False)
def test_heavy_setup(heavy_resource):
    # Упадёт, потому что фикстура заняла 4 секунды + тело теста
    time.sleep(2)
    assert True

# ВНИМАНИЕ: func_only=False включает время всех фикстур для данного теста,
# что может привести к неожиданным падениям при долгих сессионных фикстурах.
# Рекомендуется задавать таймаут с запасом или выносить медленные фикстуры
# в scope='session' и не включать их в таймаут.

# ---------------------------------------------------------------------------
# 36.5 Обработка исключения таймаута и повтор (pytest-rerunfailures)
# ---------------------------------------------------------------------------
# При срабатывании таймаута выбрасывается TimeoutError (или
# pytest_timeout.TimeoutExpired в старых версиях).
# Это считается ошибкой теста (FAILED). Можно комбинировать с flaky:

@pytest.mark.timeout(2)
@pytest.mark.flaky(reruns=1)  # если упал по таймауту, повторить 1 раз
def test_with_retry_on_timeout():
    if not hasattr(test_with_retry_on_timeout, "_attempt"):
        test_with_retry_on_timeout._attempt = True
        time.sleep(3)  # первый запуск упадёт по таймауту
    assert True

# ---------------------------------------------------------------------------
# 36.6 Важные нюансы и частые ошибки
# ---------------------------------------------------------------------------
# - На Windows метод 'signal' не поддерживается, поэтому по умолчанию используется 'thread'.
#   Если в pytest.ini указан method=signal, на Windows тесты будут запускаться без таймаутов.
# - Метод 'thread' не всегда может прервать C-расширения, которые не отпускают GIL.
#   В таких случаях тест зависнет навсегда.
# - Таймаут не применяется к хукам (setup/teardown класса, pytest_sessionstart и т.д.),
#   только к тестовым функциям и их фикстурам (если func_only=False).
# - Если тест помечен как @pytest.mark.skip или xfail, таймаут игнорируется.
# - При параллельном запуске (pytest-xdist) каждый воркер может иметь свой таймаут,
#   и плагин работает корректно.
# - Значение timeout=0 отключает таймаут для конкретного теста, даже если задан глобальный.
# - Для отладки тестов с таймаутом полезно временно увеличивать лимит или отключать его:
#   pytest --timeout=0  # запуск без таймаутов

