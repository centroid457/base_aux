# 35.2 ОБЪЕКТ CONFIG (config)
# =============================================================================
# Это экземпляр pytest.Config, доступен почти везде (через request.config,
# session.config или напрямую в хуках).

# --- Основные атрибуты ---
# config.rootdir         : корневая директория проекта (путь).
# config.inicfg          : словарь с настройками из pytest.ini.
# config.pluginmanager   : менеджер плагинов.
# config.stash           : официальное хранилище произвольных данных на время сессии
#                          (доступно с pytest 7.1, используется через ключи).
# config.option          : объект с распарсенными аргументами командной строки.
#                          config.option.verbose, config.option.htmlpath и т.д.
# config.args            : список оставшихся позиционных аргументов командной строки.

# --- Полезные методы ---
# config.getoption(name, default=...)   : получить значение опции командной строки (--key).
# config.getini(name)                   : получить значение из INI-файла ([pytest] секция).
# config.getvalue(name, path=...)       : получить значение из INI, опции или переменной окружения.
# config.addinivalue_line(name, line)   : добавить строку в список значений INI (например, markers).
# config.cache                          : объект Cache для межсессионного хранения.
# config.hook                           : менеджер хуков (для вызова своих событий).

# --- Хранилище config.stash ---
# Идеально для передачи данных между хуками и фикстурами в пределах одной сессии.
def pytest_configure(config):
    config.stash["device_id"] = "12345"

def pytest_sessionfinish(session, exitstatus):
    device = session.config.stash.get("device_id", "unknown")
    print(f"\nDevice: {device}")

# ---------------------------------------------------------------------------
# 35.3 Сравнение: stash vs cache vs глобальная переменная
# ---------------------------------------------------------------------------
# stash (config.stash)         : временное хранилище на время сессии, не влияет на следующие запуски.
#                                Идеально для передачи данных внутри одного прогона.
# cache (config.cache)         : сохраняет данные между разными сессиями pytest (в .pytest_cache/).
#                                Подходит для сохранения последнего успешного device_id и т.п.
# глобальная переменная модуля : работает, но опасно при параллельном запуске,
#                                не масштабируется, не рекомендуется.

# Пример с cache:
def test_store_device_id(config):
    config.cache.set("device_id", "ABC-001")

