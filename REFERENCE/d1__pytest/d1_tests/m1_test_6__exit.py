# Бывают ситуации, когда нужно:
#   - прервать всё тестирование при критическом условии
#   - пропустить конкретный тест
#   - пропустить весь класс
#   - пропустить класс по результату теста из другого класса/файла
#
# pytest предоставляет для этого мощные средства, но призывает избегать
# жёстких зависимостей между тестами — они должны быть изолированными.
# Тем не менее, приёмы ниже показывают, как это можно сделать.

# ---------------------------------------------------------------------------
# 18.1 Полный выход из процесса тестирования: pytest.exit()
# ---------------------------------------------------------------------------

# 1=EXIT (без настроек) ----------------------------------------------------
# просто выход из всего!!!
# дальнейшие тесты не отображаются!!!
# не очень информативен выход - не отображает выход падением - ничем не помечает тест, но визуально отображается как SKIPPED

# 2=FAIL ----------------------------------------------------
# пометка Fail текущего теста +все остальные тесты отображаются но на входе все Fail по указанной причине!!! если только они сами не SKIP-нутся первыми!!!
def test_check_critical():
    if 2 + 2 != 4:
        pytest.exit("Фундаментальная математика сломана. Дальнейшее тестирование бессмысленно.")
    assert True

# 3=EXIT (+синтетический FAIL) ----------------------------------------------------
# чтобы отобразить выход с пометкой FAIL

pytest.exit("Устройство Harvest не обнаружено", returncode=2)  # НЕ ПОМОГЛО!!! ни с одним индексом!!!



