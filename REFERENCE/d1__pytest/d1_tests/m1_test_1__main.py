# 3. ТЕСТИРОВАНИЕ ИСКЛЮЧЕНИЙ (pytest.raises)
# =============================================================================
def divide(a, b):
    if b == 0:
        raise ValueError("Деление на ноль недопустимо")
    return a / b

def test_divide_by_zero():
    with pytest.raises(ValueError, match="Деление на ноль"):
        divide(10, 0)

def test_divide_ok():
    assert divide(10, 2) == 5

