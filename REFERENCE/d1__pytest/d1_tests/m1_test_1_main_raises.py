# =============================================================================
# 55. ТЕСТИРОВАНИЕ ИСКЛЮЧЕНИЙ: pytest.raises
# =============================================================================
# pytest.raises — контекстный менеджер для проверки, что код выбрасывает
# ожидаемое исключение. Это не «поймать и забыть», а именно проверить факт
# и параметры исключения.

import pytest

# ======================================================================================================================
# 3. ТЕСТИРОВАНИЕ ИСКЛЮЧЕНИЙ (pytest.raises)
# =============================================================================
def divide(a, b):
    if b == 0:
        raise ValueError("Деление на ноль недопустимо")
    return a / b

# Можно проверять конкретный текст исключения через match (регулярное выражение).
# Если исключение не возникнет – тест упадёт.


# =============================================================================
# 55.1 БАЗОВОЕ ИСПОЛЬЗОВАНИЕ
# =============================================================================
def test_divide_by_zero():
    with pytest.raises(ValueError, match="Деление на ноль"):
        divide(10, 0)

def test_divide_ok():
    assert divide(10, 2) == 5

# Если исключение не будет выброшено — тест упадёт с сообщением
# "DID NOT RAISE ValueError".

# =============================================================================
# 55.2 ПРОВЕРКА ТЕКСТА ИСКЛЮЧЕНИЯ: match
# =============================================================================
# match — это re.search (не полное совпадение!). Учитывайте это.
# Если нужна точная строка — используйте re.escape() + ^...$.

def test_match_substring():
    with pytest.raises(ValueError, match="ноль"):
        divide(10, 0)

def test_match_regex():
    with pytest.raises(ValueError, match=r"Деление на \w+"):
        divide(10, 0)

# Частая ошибка: match с символами вроде "(", ")", "+" — это regex.
# Правильно: match=re.escape("Деление (на ноль)")

import re
def test_match_escaped():
    with pytest.raises(ValueError, match=re.escape("Деление на ноль")):
        divide(10, 0)

# =============================================================================
# 55.3 ДОСТУП К ОБЪЕКТУ ИСКЛЮЧЕНИЯ: as exc_info
# =============================================================================

def test_exception_object():
    with pytest.raises(ValueError) as exc_info:
        divide(10, 0)

    assert str(exc_info.value) == "Деление на ноль"
    assert exc_info.type is ValueError
    assert exc_info.value.args == ("Деление на ноль",)
    # exc_info.traceback — объект traceback

# =============================================================================
# 55.4 ГРУППА ИСКЛЮЧЕНИЙ: можно передать кортеж
# =============================================================================

def test_multiple_exception_types():
    with pytest.raises((ValueError, TypeError)):
        divide(10, 0)   # подойдёт любое из перечисленных

# =============================================================================
# 55.5 ПРОВЕРКА, ЧТО ИСКЛЮЧЕНИЯ НЕ БЫЛО
# =============================================================================
# Просто не оборачивайте код в pytest.raises — тест упадёт сам, если
# исключение выброшено. Но если хотите явный контроль:

def test_no_exception():
    result = divide(10, 2)
    assert result == 5

# =============================================================================
# 55.6 ВЛОЖЕННЫЕ ИСКЛЮЧЕНИЯ И КОНТЕКСТ
# =============================================================================
# Если исключение выбрасывается из блока except другого исключения,
# можно проверить цепочку через __cause__ / __context__.

def nested_raise():
    try:
        int("abc")
    except ValueError as e:
        raise RuntimeError("Ошибка парсинга") from e

def test_chained_exception():
    with pytest.raises(RuntimeError) as exc_info:
        nested_raise()
    assert isinstance(exc_info.value.__cause__, ValueError)

# =============================================================================
# 55.7 pytest.raises В ФИКСТУРАХ И ХУКАХ
# =============================================================================
# В фикстурах pytest.raises работает так же, но есть нюанс: если исключение
# не выброшено, фикстура упадёт с DID NOT RAISE — и тест получит ошибку
# в setup, а не в call.

@pytest.fixture
def broken_setup():
    with pytest.raises(ValueError):
        divide(10, 0)   # здесь ожидается исключение
    return "ok"

def test_using_fixture(broken_setup):
    assert broken_setup == "ok"

# =============================================================================
# 55.8 АЛЬТЕРНАТИВА: pytest.warns и pytest.deprecated_call
# =============================================================================
import warnings

def emit_warning():
    warnings.warn("Устаревшая функция", DeprecationWarning)

def test_warning():
    with pytest.warns(DeprecationWarning, match="Устаревшая"):
        emit_warning()

def test_deprecated():
    with pytest.deprecated_call():
        emit_warning()

# =============================================================================
# 55.9 ЧАСТЫЕ ОШИБКИ
# =============================================================================
# 1. Забыть, что match — это re.search, а не равенство строк. "ноль" найдёт
#    "Деление на ноль", но "Деление на ноль" не найдёт "Ошибка: Деление на ноль"
#    в начале строки (нужен ^).
# 2. Использовать "==" для строки исключения: str(exc_info.value) == "...".
#    Лучше через match или .value.args.
# 3. pytest.raises без ожидания исключения (пустой блок) — тест всегда падает.
# 4. Ожидать конкретный класс, а ловить родителя: pytest.raises(Exception)
#    поймает и ValueError, и TypeError — слишком широко.
# 5. Не учитывать, что некоторые исключения pytest перехватывает сам
#    (Skipped, Failed, Exit) — их ловить в pytest.raises нельзя, будет
#    странное поведение.
# 6. pytest.raises нельзя использовать вне теста/фикстуры (например, в
#    pytest_configure) — там нет контекста pytest и не сработает.

# =============================================================================
# 55.10 РЕКОМЕНДАЦИИ
# =============================================================================
# - Всегда указывайте конкретный класс исключения, а не Exception.
# - Используйте match для проверки смысла ошибки, а не только типа.
# - Если нужно проверить несколько атрибутов исключения — используйте as exc_info.
# - Для проверки отсутствия исключения просто вызывайте код без обёртки.
# - Для предупреждений — pytest.warns, а не pytest.raises(Warning).