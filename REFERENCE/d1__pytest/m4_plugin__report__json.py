# 37.6 Совместное использование с другими плагинами
# ---------------------------------------------------------------------------
# pytest-html и pytest-json-report могут работать одновременно:
# pytest --html=report.html --json-report --json-report-file=report.json

# При параллельном запуске (pytest-xdist) JSON-отчёт объединяется корректно,
# если использовать --json-report-file с одним файлом – он будет содержать
# результаты всех воркеров.

# ---------------------------------------------------------------------------
# 37.7 Частые ошибки и особенности
# ---------------------------------------------------------------------------
# - Если не указан --json-report-file, файл не создаётся (вывод только в консоли при --json-report-summary).
# - Для получения полного отчёта всегда используйте --json-report.
# - Плагин записывает отчёт в конце сессии. При аварийном завершении файл может остаться пустым
#   или отсутствовать (решается аналогично решению для HTML через pytest_unconfigure).
# - При большом количестве тестов JSON может быть огромным – используйте --json-report-omit=streams
#   для исключения громоздких захваченных логов.
# - Перезапуск с --lf не обновляет старый JSON-файл, если имя файла не уникально;
#   используйте динамические имена (timestamp).


