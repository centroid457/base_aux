# ---------------------------------------------------------------------------
# 37.4 Добавление своих метаданных в отчёт (хуки)
# ---------------------------------------------------------------------------
# Можно добавить произвольные поля через объект report.

def test_with_custom_metadata(record_property):
    record_property("severity", "high")
    record_property("feature", "login")
    assert True

# Эти свойства появятся в JSON в разделе "user_properties" для теста.

# Для глобальных метаданных используйте хук pytest_sessionfinish:
def pytest_sessionfinish(session, exitstatus):
    if hasattr(session.config, "_json_report"):
        # Доступ к отчёту до его сохранения
        report = session.config._json_report
        report["custom_metadata"] = {"environment": "staging"}

