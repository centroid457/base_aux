# Плагин для создания машиночитаемого отчёта в формате JSON.
# Установка: pip install pytest-json-report
# ---------------------------------------------------------------------------
# 37.1 Базовый запуск и вывод JSON-отчёта
# ---------------------------------------------------------------------------
# Сгенерировать отчёт test_report.json:
# pytest --json-report --json-report-file=test_report.json

# Краткая сводка в консоли (без создания файла):
# pytest --json-report --json-report-summary

# Отключить консольный вывод, только JSON:
# pytest --json-report --json-report-file=report.json -q

# ---------------------------------------------------------------------------
# 37.2 Основные параметры командной строки
# ---------------------------------------------------------------------------
# --json-report                  : включить генерацию JSON-отчёта
# --json-report-file=PATH        : путь к файлу отчёта (по умолчанию report.json)
# --json-report-indent=4         : форматированный вывод с отступами (по умолчанию None — компактный JSON)
# --json-report-omit=log         : исключить из отчёта определённые поля (log, streams, traceback и др.)
# --json-report-omit=streams     : не включать захваченный stdout/stderr
# --json-report-summary          : вывести только сводку в консоль, не создавая файл

# ---------------------------------------------------------------------------
# 37.3 Структура JSON-отчёта
# ---------------------------------------------------------------------------
# Пример минимального тестового файла и результирующего JSON.

def test_passing_json():
    assert 1 + 1 == 2

def test_failing_json():
    assert 1 + 1 == 3

# После запуска: pytest --json-report --json-report-file=report.json -v
# Содержимое report.json будет примерно таким:
# {
