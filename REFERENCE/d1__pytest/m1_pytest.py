_previous_test_passed = False


def test__prerequisite():
    global _previous_test_passed
    # Имитируем, что какой-то важный предусловительный тест прошёл
    _previous_test_passed = True
    assert True


class Test__DependentOnPrevious:
    @classmethod
    def setup_class(cls):
        if not _previous_test_passed:
            pytest.skip("Предварительный тест не прошёл — класс пропущен")

    def test_needs_prereq(self):
        assert True  # выполнится, только если _previous_test_passed == True


