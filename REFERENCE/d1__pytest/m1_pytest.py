# 18.8 Важные предостережения и частые ошибки
# ---------------------------------------------------------------------------
# - Глобальные переменные для межтестового общения: порядок тестов
#   может измениться, если использовать случайный порядок (--random-order),
#   или при параллельном запуске. Лучше избегать таких зависимостей.
#
