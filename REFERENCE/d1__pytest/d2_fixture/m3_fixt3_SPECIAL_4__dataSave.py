# =============================================================================
# 48. ХРАНЕНИЕ ДАННЫХ В PYTEST: ВСЕ УРОВНИ И МЕХАНИЗМЫ
# =============================================================================
# В pytest есть несколько независимых хранилищ, каждое со своим временем
# жизни, областью видимости и способом сериализации. Ниже — полная карта.

import pytest
import os

# =============================================================================
# 48.1 ЛОКАЛЬНЫЕ ПЕРЕМЕННЫЕ И АТРИБУТЫ УЗЛОВ (только на время теста)
# =============================================================================
# Самый простой уровень — обычные переменные внутри теста или фикстуры.
# Живут до конца теста/фикстуры, не сериализуются, недоступны снаружи.

def test_local():
    value = 42
    assert value == 42

# Атрибуты узла теста: item (доступен через request.node) — можно вешать
# произвольные атрибуты, живут до конца теста.
def test_node_attr(request):
    request.node.custom_data = "hello"
    assert request.node.custom_data == "hello"

# =============================================================================
# 48.2 FIXTURE CACHING: результат фикстуры кешируется в рамках её scope
# =============================================================================
# Значение, возвращаемое фикстурой, сохраняется в кеше и переиспользуется
# всеми тестами в пределах scope. Не требует сериализации, живёт в памяти.

@pytest.fixture(scope="session")
def shared_config():
    return {"env": "test"}  # вычисляется один раз на сессию

# =============================================================================
# 48.3 CONFIG.STASH — словарь объектов на время одной сессии pytest
# =============================================================================
# Появился в pytest 7.1. Официальное временное хранилище произвольных данных.
# Не сериализуется, живёт только в рамках текущего процесса pytest.
# Идеально для передачи данных между хуками и фикстурами.

def pytest_configure(config):
    config.stash["device_id"] = "COM3"  # любой объект: dict, list, class

def pytest_sessionfinish(session, exitstatus):
    device = session.config.stash.get("device_id", None)
    print(f"\nУстройство: {device}")

# Доступ из теста через config:
def test_stash_access(config):
    config.stash["test_marker"] = 123
    assert config.stash.get("test_marker") == 123

# Удаление:
def test_stash_delete(config):
    config.stash.pop("test_marker", None)

# =============================================================================
# 48.4 CONFIG.CACHE — межсессионное хранилище (СЕРИАЛИЗАЦИЯ В JSON)
# =============================================================================
# Фикстура cache (и config.cache) сохраняет данные между запусками pytest
# в директории .pytest_cache/v/cache/. Данные сериализуются в JSON.
# Работает только с JSON-совместимыми типами: str, int, float, bool, None,
# list, dict (с JSON-совместимыми ключами/значениями).

def test_cache_set(cache):
    cache.set("last_device", "COM3")
    cache.set("counter", 42)
    cache.set("config", {"baud": 115200, "parity": "N"})

def test_cache_get(cache):
    device = cache.get("last_device", "NONE")
    counter = cache.get("counter", 0)
    cfg = cache.get("config", {})
    assert device in ("COM3", "NONE")
    assert isinstance(counter, int)

# Ограничения:
# - Нельзя положить объект класса, файловый дескриптор, lambda.
# - Всё, что не сериализуется в JSON, вызовет ошибку при set.

# Путь к файлу кеша:
def test_cache_path(cache):
    print(f"\nКеш хранится в: {cache._cachedir}")

# =============================================================================
# 48.5 RECORD_PROPERTY — свойства теста для отчётов (function scope)
# =============================================================================
# Добавляет пары key/value в объект тестового отчёта. Не сохраняется между
# тестами, не доступно из других тестов. Используется плагинами отчётов
# (pytest-html, pytest-json-report).

def test_with_properties(record_property):
    record_property("device", "BT-001")
    record_property("severity", "critical")
    record_property("tags", ["smoke", "fast"])  # списки тоже поддерживаются

# =============================================================================
# 48.6 RECORD_TESTSUITE_PROPERTY — свойства на всю сессию (session scope)
# =============================================================================
# Записывает свойства в корневой элемент JUnit XML-отчёта.
# Можно вызвать только один раз за сессию (обычно в session-фикстуре).

@pytest.fixture(scope="session", autouse=True)
def record_suite_info(record_testsuite_property):
    record_testsuite_property("environment", "staging")
    record_testsuite_property("build", os.environ.get("BUILD_ID", "local"))

# Эти свойства не доступны из тестов (только запись в отчёт).

# =============================================================================
# 48.7 RECORD_XUNIT_PROPERTY — низкоуровневая запись в JUnit XML
# =============================================================================
# Более гибкий, но менее удобный. Позволяет задать properties внутри
# конкретного testcase (в отличие от testsuite-level).

def test_xunit(record_xunit_property):
    record_xunit_property("my_key", "my_value")
    # В XML появится <property name="my_key" value="my_value"/>

# =============================================================================
# 48.8 CACHE ПЛАГИНОВ: pytest-json-report и другие
# =============================================================================
# Некоторые плагины используют свой кеш. Например, pytest-json-report держит
# данные в config._json_report. Не рекомендуется использовать эти внутренние
# структуры напрямую — они могут меняться.

# =============================================================================
# 48.9 СВОДНАЯ ТАБЛИЦА
# =============================================================================
# Механизм                  | Scope       | Сериализация | Между сессиями | Доступ из тестов
# --------------------------|-------------|--------------|----------------|-------------------
# Локальные переменные      | тест        | нет          | нет            | только внутри
# item.attr (request.node)  | тест        | нет          | нет            | через request
# Fixture caching           | по scope    | нет          | нет            | через фикстуру
# config.stash              | сессия      | нет          | нет            | да (через config)
# config.cache / cache      | сессия +    | JSON         | ДА             | да (через cache)
# record_property           | тест        | зависит от   | нет            | нет (только запись)
#                           |             | плагина      |                |
# record_testsuite_property | сессия      | зависит      | нет            | нет (только запись)
# record_xunit_property     | тест        | XML          | нет            | нет (только запись)

# =============================================================================
# 48.10 РЕКОМЕНДАЦИИ ПО ВЫБОРУ
# =============================================================================
# - Нужно передать данные внутри одной сессии между хуками/фикстурами?
#   → config.stash (объекты в памяти, быстрее, без сериализации).
#
# - Нужно сохранить что-то между запусками (например, ID последнего устройства)?
#   → cache (только JSON-совместимое).
#
# - Нужно записать информацию в отчёт (HTML/JSON/XML)?
#   → record_property (для теста) или record_testsuite_property (для сессии).
#
# - Нужно передать данные между тестами в рамках одной сессии?
#   → config.stash или фикстура с широким scope. НЕ используйте глобальные
#     переменные модуля — они не работают при xdist и небезопасны.
#
# - Нужно передать данные в подпроцессы (xdist-воркеры)?
#   → config.cache (файлы), но будьте готовы к гонкам. Либо — переменные
#     окружения и файлы с блокировками.


