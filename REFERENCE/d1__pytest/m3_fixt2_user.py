# Иногда нужно, чтобы фикстура возвращала не готовый объект,
# а функцию-фабрику для создания объектов с параметрами.
@pytest.fixture
def make_user():
    """Фабрика пользователей."""
    created = []
    def _make(name, age):
        user = {"name": name, "age": age}
        created.append(user)
        return user
    yield _make
    # teardown: можно удалить всех созданных пользователей
    print(f"\n\t[Фикстура make_user] удалено пользователей: {len(created)}")

def test_user_factory(make_user):
    user1 = make_user("Alice", 30)
    user2 = make_user("Bob", 25)
    assert user1["name"] == "Alice"
    assert len(user1) == 2  # упадёт, чтобы показать ошибку; замените на 2
    # Покажем правильное:
    # assert len(user1) == 2

# Параметризация самой фикстуры (pytest >= 5.0)
# Можно передать params, и тест будет вызван для каждого значения,
# а фикстура вернёт соответствующее значение через request.param.
@pytest.fixture(params=["mysql", "postgresql", "sqlite"])
def db_backend(request):
    print(f"\n\t[Фикстура db_backend] настройка для {request.param}")
    return request.param

def test_db_connection(db_backend):
    # Этот тест запустится 3 раза с разными бэкендами
    assert db_backend in ["mysql", "postgresql", "sqlite"]









