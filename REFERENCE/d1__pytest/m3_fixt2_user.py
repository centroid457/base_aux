# 4. ОБЛАСТЬ ДЕЙСТВИЯ ФИКСТУР (scope)
# ----------------------------------------------------------------------------------------------------------------------
# По умолчанию scope="function" – фикстура выполняется для каждого теста.
# scope="module" – один раз на модуль.
# scope="class" – один раз на класс

@pytest.fixture(scope="module")
def module_db():
    """Дорогая фикстура: создаём БД один раз для всех тестов модуля."""
    print("\n\t[Фикстура module_db] ПОДКЛЮЧЕНИЕ К БД (один раз за модуль)")
    db = {"connected": True}
    yield db
    print("\n\t[Фикстура module_db] ОТКЛЮЧЕНИЕ ОТ БД")

def test_db_read(module_db):
    assert module_db["connected"] is True

def test_db_write(module_db):
    # Та же фикстура, что и выше, повторно не создаётся.
    module_db["data"] = "important"
    assert "data" in module_db

