// -------- 10. BEST PRACTICES (РЕКОМЕНДАЦИИ) --------

/*
1. ВСЕГДА добавляйте = {} для объекта в параметрах, чтобы избежать ошибок при вызове без аргументов.
2. Используйте rest вместо arguments – он чище, работает со стрелками и даёт настоящий массив.
3. Не злоупотребляйте глубокой вложенностью – если деструктуризация становится слишком сложной, лучше разбить на несколько шагов.
4. Rest-параметр должен быть последним, иначе синтаксическая ошибка.
5. Деструктурируйте только те свойства, которые действительно нужны – избегайте избыточности.
6. Для функций с большим количеством параметров (более 3-4) лучше использовать объект опций с деструктуризацией – это упрощает добавление новых параметров без изменения порядка.
7. При переименовании свойств давайте понятные имена, например { name: userName }.
8. В деструктуризации массива пропускайте неиспользуемые элементы с помощью запятой: [,,third] – но лучше избегать ради читаемости.
9. Используйте spread для вызова функций с динамическим числом аргументов (например, Math.max(...array)).
10. Комментируйте сложные деструктуризации, чтобы облегчить понимание другим разработчикам (и себе в будущем).
11. Если функция вызывается часто, избегайте глубокой деструктуризации внутри – это может снизить производительность (не критично, но стоит иметь в виду).
12. В TypeScript деструктуризация с типами выглядит так: function({ a, b }: { a: number; b: string }) { ... }
*/

// -------- 11. ВАЖНЫЕ МОМЕНТЫ --------

/*
- Оператор ... имеет разные названия в зависимости от контекста:
    * В параметрах – rest (собирает)
    * При вызове – spread (распространяет)
    * В деструктуризации – rest (собирает остаток)
- Rest всегда возвращает массив (для параметров) или объект (для деструктуризации объекта).
- Значения по умолчанию применяются, если свойство отсутствует или равно undefined (не применяются для null).
- При деструктуризации объекта можно использовать вычисляемые ключи: { [key]: value }.
- Вложенная деструктуризация может иметь свои значения по умолчанию.
- Функции с деструктуризацией можно вызывать без аргументов, если выставлено = {}.
- В стрелочных функциях деструктуризация работает так же, как и в обычных.
- Для массивов деструктуризация позиционная, для объектов – по имени свойства.
*/

